// {name} placeholders; a missing parameter stays visible so a bug is noticed rather than hidden.
// Bangla gets Bengali digits in the template and in numeric parameters; text parameters (names, rule ids, times that are already
// localised) are inserted exactly as given.
export function t(lang, key, params = {}) {
  const raw = STRINGS[lang]?.[key] ?? STRINGS.en[key] ?? key;
  const template = lang === 'bn' ? digits(raw, 'bn') : raw;
  return template.replace(/\{(\w+)\}/g, (match, name) => {
    const value = params[name];
    if (value === undefined || value === null) return match;
    return typeof value === 'number' ? digits(value, lang) : String(value);
  });
}
